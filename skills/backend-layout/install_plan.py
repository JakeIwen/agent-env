"""Planning an install of the backend-layout checks into a repo: the files to copy, the `layout`
config block, and the suite wiring, as a Plan the command line (install-checks.py) prints or applies."""
import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

from checks.backend_layout import json_splice

SKILL = Path(__file__).resolve().parent
CHECKS = SKILL / "checks"
CONSOLIDATE = SKILL.parent / "consolidate"
MIRRORED = ("import_graph.py", "cochange.py")  # consolidate owns these; the skill keeps hash-checked copies
TEST_PATTERN = "test_layout*.py"
SUITES = ("run_tests", "npm", "unittest", "none")
COMMANDS_LIST = re.compile(r"^(?P<indent>[ \t]*)(?:commands|COMMANDS|suites|SUITES)\s*=\s*\[[ \t]*$", re.MULTILINE)
COLLECTS_TESTS = re.compile(r"""startswith\(\s*['"]test_['"]|['"]test_\*\.py['"]""")
DISCOVERY_ROOT = re.compile(r"unittest discover[^\n`]*?-s\s+([^\s`'\"]+)")
GENERATED_TEST = '''"""Runs the backend-layout checks installed in {scripts}/ (their fixture tests and the repo's own
tree), so this unittest suite covers them. Generated by the backend-layout skill's installer."""
import subprocess
import sys
import unittest
from pathlib import Path

CHECKS = Path(__file__).resolve().parents[{depth}] / "{scripts}"


class BackendLayoutChecks(unittest.TestCase):
    def test_layout_checks_pass(self):
        result = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", str(CHECKS),
                                 "-p", "{pattern}"], capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
'''


@dataclass
class Plan:
    files: Dict[str, bytes] = field(default_factory=dict)  # repo-relative path -> new content
    unchanged: List[str] = field(default_factory=list)
    conflicts: Dict[str, bytes] = field(default_factory=dict)  # installed files that differ: path -> ours
    notes: List[str] = field(default_factory=list)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sources(scripts: str) -> Dict[str, Path]:
    out = {f"{scripts}/check_layout.py": CHECKS / "check_layout.py"}
    out.update({f"{scripts}/backend_layout/{p.name}": p for p in sorted((CHECKS / "backend_layout").glob("*.py"))})
    tests = sorted((SKILL / "tests").glob("test_layout_*.py")) + [SKILL / "tests" / "layout_fixture.py"]
    out.update({f"{scripts}/{p.name}": p for p in tests})
    out[f"{scripts}/test_layout_tree.py"] = SKILL / "templates" / "test_layout_tree.py"
    return out


def stage(repo: Path, rel: str, content: bytes, plan: Plan):
    """Queue a file the installer owns; an existing copy that differs (edited, or from an older skill) is
    a conflict, overwritten only with --force."""
    target = repo / rel
    if target.exists() and target.read_bytes() == content:
        plan.unchanged.append(rel)
    elif target.exists():
        plan.conflicts[rel] = content
    else:
        plan.files[rel] = content


def plan_copies(repo: Path, scripts: str, plan: Plan):
    for rel, source in sources(scripts).items():
        stage(repo, rel, source.read_bytes(), plan)


def default_layout(scripts: str) -> dict:
    return {"sourceRoots": ["."], "entries": [], "contracts": [],
            "exclude": [f"{scripts}/check_layout.py", f"{scripts}/backend_layout", f"{scripts}/layout_fixture.py"],
            "exceptions": []}


def plan_config(repo: Path, scripts: str, plan: Plan):
    rel, path = ".codeshape/config.json", repo / ".codeshape" / "config.json"
    if not path.exists():
        text = json.dumps({"layout": default_layout(scripts)}, indent=2) + "\n"
    else:
        current = path.read_text(encoding="utf-8")
        if "layout" in json.loads(current):
            plan.unchanged.append(rel + " (layout block present)")
            return
        text = json_splice.set_key(current, "layout", default_layout(scripts), sort_keys=False)
    plan.files[rel] = text.encode("utf-8")


def detect_suite(repo: Path) -> Optional[str]:
    if (repo / "run_tests.py").is_file():
        return "run_tests"
    package = repo / "package.json"
    if package.is_file() and (json.loads(package.read_text(encoding="utf-8")).get("scripts") or {}).get("test"):
        return "npm"
    return "unittest" if (repo / "tests").is_dir() or discovery_root(repo) else None


def plan_run_tests(repo: Path, scripts: str, plan: Plan):
    path = repo / "run_tests.py"
    text = path.read_text(encoding="utf-8")
    if TEST_PATTERN in text:
        plan.unchanged.append("run_tests.py (already runs the layout tests)")
        return
    m = COMMANDS_LIST.search(text)
    if not m:
        plan.notes.append("run_tests.py collects test_*.py files itself; the installed tests need no step."
                          if COLLECTS_TESTS.search(text) else
                          f"run_tests.py has no `commands = [` list: add a step running `python3 -m unittest "
                          f"discover -s {scripts} -p '{TEST_PATTERN}'` by hand.")
        return
    following = text[m.end() + 1:].split("\n", 1)[0]
    indent = re.match(r"[ \t]*", following).group(0) or m.group("indent") + "    "
    python = "sys.executable" if re.search(r"^import sys\b|^import .*\bsys\b", text, re.MULTILINE) else "'python3'"
    step = f"{indent}[{python}, '-m', 'unittest', 'discover', '-s', '{scripts}', '-p', '{TEST_PATTERN}'],\n"
    plan.files["run_tests.py"] = (text[:m.end() + 1] + step + text[m.end() + 1:]).encode("utf-8")


def plan_npm(repo: Path, scripts: str, plan: Plan):
    path = repo / "package.json"
    raw = path.read_text(encoding="utf-8")
    pkg = json.loads(raw)
    commands = pkg.setdefault("scripts", {})
    before = dict(commands)
    commands["check:layout"] = f"python3 {scripts}/check_layout.py"
    commands["test:layout"] = f"python3 -m unittest discover -s {scripts} -p '{TEST_PATTERN}'"
    test = commands.get("test", "")
    if "test:layout" not in test:
        placeholder = not test or "no test specified" in test
        commands["test"] = "npm run test:layout" if placeholder else f"{test} && npm run test:layout"
    if commands == before:
        plan.unchanged.append("package.json (layout scripts present)")
        return
    indent = re.search(r'^(\s+)"', raw, re.MULTILINE)
    text = json.dumps(pkg, indent=indent.group(1) if indent else 2, ensure_ascii=False) + "\n"
    plan.files["package.json"] = text.encode("utf-8")


def discovery_root(repo: Path) -> Optional[str]:
    for doc in ("AGENTS.md", "README.md"):
        path = repo / doc
        m = DISCOVERY_ROOT.search(path.read_text(encoding="utf-8", errors="replace")) if path.is_file() else None
        if m and (repo / m.group(1)).is_dir():
            return m.group(1).rstrip("/")
    return None


def plan_unittest(repo: Path, scripts: str, plan: Plan):
    root = discovery_root(repo) or "tests"
    depth = len(Path(root).parts)
    text = GENERATED_TEST.format(scripts=scripts, depth=depth, pattern=TEST_PATTERN)
    stage(repo, f"{root}/test_backend_layout.py", text.encode("utf-8"), plan)


def plan_suite(repo: Path, scripts: str, suite: Optional[str], plan: Plan):
    suite = suite or detect_suite(repo)
    if suite in (None, "none"):
        plan.notes.append(f"No suite wired: add `python3 -m unittest discover -s {scripts} -p '{TEST_PATTERN}'` "
                          f"to the repo's documented test command.")
        return
    {"run_tests": plan_run_tests, "npm": plan_npm, "unittest": plan_unittest}[suite](repo, scripts, plan)
    plan.notes.insert(0, f"suite: {suite}")


def mirrored_drift() -> List[str]:
    return [name for name in MIRRORED if (CONSOLIDATE / name).is_file()
            and sha256(CONSOLIDATE / name) != sha256(CHECKS / "backend_layout" / name)]


def apply(repo: Path, plan: Plan):
    for rel, content in plan.files.items():
        target = repo / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
